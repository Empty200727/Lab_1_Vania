# Задание 07. Секретное сообщение.
# Слово 1 - 4-я буква; слово 2 - буквы 10-13; слово 3 - буквы 6-15 через одну;
# слово 4 - буквы 8-13 задом наперёд; слово 5 - буквы 17-21 задом наперёд.

TITLE = 'Расшифровка сообщения'

secret_message = [
    'квевтфпп6щ3стмзалтнмаршгб5длгуча',
    'дьсеы6лц2бане4т64ь4б3ущея6втщл6б',
    'т3пплвце1н3и2кд4лы12чф1ап3бкычаь',
    'ьд5фму3ежородт9г686буиимыкучшсал',
    'бсц59мегщ2лятьаьгенедыв9фк9ехб1а',
]

# (номер строки, начало, конец, шаг) - уже в индексах
RULES = [
    (0, 3, 4, 1),
    (1, 9, 13, 1),
    (2, 5, 15, 2),
    (3, 12, 6, -1),
    (4, 20, 15, -1),
]


def decrypt(message):
    phrase = ''
    for row, start, stop, step in RULES:
        phrase += message[row][start:stop:step] + ' '
    return phrase.strip()


def run():
    print(decrypt(secret_message))


if __name__ == '__main__':
    run()
